#!/usr/bin/env python3
"""Prepare dashboard assets and append them outside an executable's mappings."""

import argparse
import hashlib
import os
from pathlib import Path
import struct
import tempfile


ROOT = Path(__file__).resolve().parent.parent
NAMES = ("style.css", "app.js", "index.html")
MAGIC = b"QUECTOPA"


def prepare(directory: Path) -> None:
    """Hash the exact served bytes and generate the collector's tiny manifest."""
    assets = [
        (directory / name if name == "app.js" else ROOT / "web" / name).read_bytes()
        for name in NAMES
    ]
    digest = hashlib.sha256()
    for name, data in zip(NAMES, assets):
        digest.update(name.encode("ascii") + b"\0")
        digest.update(struct.pack("<Q", len(data)))
        digest.update(data)
    revision = digest.hexdigest()[:16]
    sizes = ", ".join(str(len(data)) for data in assets)
    header = (
        "/* Generated by scripts/assets.py; only metadata is mapped. */\n"
        f'#define QUECTOP_ASSETS_REVISION "{revision}\\n"\n'
        f"static const u32 asset_sizes[] = {{{sizes}}};\n"
    )
    (directory / "assets.h").write_text(header, encoding="ascii")
    (directory / "assets.bin").write_bytes(b"".join(assets))


def pack(binary: Path, output: Path, directory: Path) -> None:
    """Append a page-isolated payload, leaving every ELF program header intact."""
    executable = binary.read_bytes()
    if executable[:4] != b"\x7fELF" or executable[4] not in (1, 2) or executable[5] not in (1, 2):
        raise ValueError("expected a 32-bit or 64-bit ELF executable")
    elf64 = executable[4] == 2
    byte_order = "<" if executable[5] == 1 else ">"
    machine = struct.unpack_from(byte_order + "H", executable, 18)[0]
    # ARM64 kernels can use 4/16/64 KiB pages; AMD64 uses 4 KiB base pages.
    alignment = {40: 65536, 62: 4096, 183: 65536}.get(machine)
    if alignment is None:
        raise ValueError(f"unsupported ELF machine: {machine}")
    phoff = struct.unpack_from(byte_order + ("Q" if elf64 else "I"), executable, 32 if elf64 else 28)[0]
    phsize, phcount = struct.unpack_from(byte_order + "HH", executable, 54 if elf64 else 42)
    if phsize != (56 if elf64 else 32) or phoff + phsize * phcount > len(executable):
        raise ValueError("invalid ELF program headers")
    mapped_end = 0
    for index in range(phcount):
        fields = struct.unpack_from(byte_order + ("IIQQQQQQ" if elf64 else "8I"),
                                    executable, phoff + index * phsize)
        kind = fields[0]
        offset, size = (fields[2], fields[5]) if elf64 else (fields[1], fields[4])
        if kind == 1 and size:
            if offset + size > len(executable):
                raise ValueError("ELF loadable segment exceeds file size")
            mapped_end = max(mapped_end, offset + size)
    if not mapped_end:
        raise ValueError("ELF has no loadable segments")
    payload_at = (max(len(executable), mapped_end) + alignment - 1) // alignment * alignment
    payload = (directory / "assets.bin").read_bytes()
    output.parent.mkdir(parents=True, exist_ok=True)
    # Replace atomically so rebuilding never truncates a running executable.
    fd, temporary = tempfile.mkstemp(prefix=f".{output.name}.", dir=output.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(executable)
            stream.write(b"\0" * (payload_at - len(executable)))
            stream.write(payload)
            stream.write(MAGIC + struct.pack("<Q", len(payload)))
            os.fchmod(stream.fileno(), binary.stat().st_mode & 0o777)
        os.replace(temporary, output)
    finally:
        Path(temporary).unlink(missing_ok=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    preparing = commands.add_parser("prepare", help="generate payload and C manifest")
    preparing.add_argument("directory", type=Path)
    packing = commands.add_parser("pack", help="append payload to a linked executable")
    packing.add_argument("binary", type=Path)
    packing.add_argument("output", type=Path)
    packing.add_argument("directory", type=Path)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.directory)
    else:
        pack(args.binary, args.output, args.directory)


if __name__ == "__main__":
    main()
