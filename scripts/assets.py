#!/usr/bin/env python3
"""Stage the dashboard assets that quectop-hub embeds and their revision."""

import argparse
import hashlib
from pathlib import Path
import re
import struct


ROOT = Path(__file__).resolve().parent.parent
NAMES = ("style.css", "app.js", "index.html")


def prepare(directory: Path) -> None:
    """Hash the exact served bytes and generate the hub's revision header.

    Bun has already minified app.js and style.css into the directory. The page
    gets its icons inlined and loses the whitespace between its tags.
    """
    page = (ROOT / "web" / "index.html").read_text(encoding="utf-8")
    page = re.sub(r"<!--icon:([a-z-]+)-->",
                  lambda m: (ROOT / "web" / "icons" / f"{m[1]}.svg").read_text(encoding="utf-8").strip(), page)
    (directory / "index.html").write_text(re.sub(r">\s+<", "><", page).strip() + "\n", encoding="utf-8")
    assets = [(directory / name).read_bytes() for name in NAMES]
    digest = hashlib.sha256()
    for name, data in zip(NAMES, assets):
        digest.update(name.encode("ascii") + b"\0")
        digest.update(struct.pack("<Q", len(data)))
        digest.update(data)
    revision = digest.hexdigest()[:16]
    header = (
        "/* Generated by scripts/assets.py. */\n"
        f'#define QUECTOP_ASSETS_REVISION "{revision}"\n'
    )
    (directory / "assets.h").write_text(header, encoding="ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    preparing = commands.add_parser("prepare", help="stage assets and generate the revision header")
    preparing.add_argument("directory", type=Path)
    args = parser.parse_args()
    prepare(args.directory)


if __name__ == "__main__":
    main()
